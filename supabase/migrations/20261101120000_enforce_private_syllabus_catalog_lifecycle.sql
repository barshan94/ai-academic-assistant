-- Enforce the private syllabus catalogue lifecycle at the database boundary.
-- Shared reference catalogues already have a stricter curator-specific guard.
create or replace function public.guard_private_syllabus_catalog_lifecycle()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if new.status <> 'draft' then
      raise exception 'Private syllabus catalogues must be created as drafts'
        using errcode = '23514';
    end if;
    if new.source_checked_at is not null then
      raise exception 'A source can only be marked checked during database verification'
        using errcode = '23514';
    end if;
    if new.owner_id is distinct from (select auth.uid())
      and current_user not in ('service_role', 'postgres') then
      raise exception 'Catalogue owner must match the authenticated user'
        using errcode = '42501';
    end if;
    return new;
  end if;

  if new.owner_id is distinct from old.owner_id then
    raise exception 'A syllabus catalogue cannot be transferred to another owner'
      using errcode = '23514';
  end if;

  if old.status = 'retired' then
    raise exception 'A retired syllabus catalogue is immutable'
      using errcode = '23514';
  end if;

  if old.status = 'verified' then
    if new.status not in ('verified', 'retired') then
      raise exception 'A verified syllabus catalogue can only remain verified or be retired'
        using errcode = '23514';
    end if;
    return new;
  end if;

  -- Drafts may remain drafts, be verified, or be retired. The timestamp is
  -- generated by PostgreSQL and cannot be pre-filled or backdated by a client.
  if new.status = 'draft' then
    if new.source_checked_at is distinct from old.source_checked_at then
      raise exception 'Source-check timestamps are set only by the verification transition'
        using errcode = '23514';
    end if;
    return new;
  end if;

  if new.status = 'retired' then
    if new.source_checked_at is distinct from old.source_checked_at then
      raise exception 'Retiring a draft cannot alter its source-check timestamp'
        using errcode = '23514';
    end if;
    return new;
  end if;

  if new.status = 'verified' then
    if new.source_url is null
      or new.source_url !~ '^https://[^[:space:]/?#]+([/?#]|$)'
      or new.source_title is null
      or length(btrim(new.source_title)) = 0 then
      raise exception 'Verification requires an HTTPS source URL and a source title'
        using errcode = '23514';
    end if;

    if not exists (
      select 1
      from public.syllabus_chapters as chapter
      where chapter.catalog_id = old.id
        and chapter.owner_id = old.owner_id
    ) then
      raise exception 'A syllabus catalogue must contain at least one chapter before verification'
        using errcode = '23514';
    end if;

    new.source_checked_at := clock_timestamp();
    return new;
  end if;

  raise exception 'Invalid syllabus catalogue lifecycle transition'
    using errcode = '23514';
end;
$$;

revoke all on function public.guard_private_syllabus_catalog_lifecycle()
  from public, anon, authenticated;

drop trigger if exists syllabus_catalogs_lifecycle_guard
  on public.syllabus_catalogs;
create trigger syllabus_catalogs_lifecycle_guard
before insert or update on public.syllabus_catalogs
for each row
execute function public.guard_private_syllabus_catalog_lifecycle();

comment on function public.guard_private_syllabus_catalog_lifecycle() is
  'Enforces private syllabus catalogue draft/verified/retired transitions, server-generated source-check timestamps, immutable ownership and minimum verification provenance.';
